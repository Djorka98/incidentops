ALTER TABLE users
    ADD COLUMN preferred_language VARCHAR(2) NOT NULL DEFAULT 'es';

ALTER TABLE users
    ADD CONSTRAINT users_preferred_language_check
        CHECK (preferred_language IN ('es', 'en'));

ALTER TABLE password_reset_tokens
    ADD COLUMN requested_language VARCHAR(2);

ALTER TABLE password_reset_tokens
    ADD CONSTRAINT password_reset_tokens_language_check
        CHECK (requested_language IS NULL OR requested_language IN ('es', 'en'));

ALTER TABLE security_events DROP CONSTRAINT security_events_type_check;
ALTER TABLE security_events
    ADD CONSTRAINT security_events_type_check CHECK (
        event_type IN (
            'PASSWORD_CHANGED',
            'PASSWORD_RESET_REQUESTED',
            'PASSWORD_RESET_COMPLETED',
            'NEW_SIGN_IN'
        )
    );

CREATE TABLE transactional_email_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    event_type VARCHAR(40) NOT NULL,
    user_id BIGINT,
    recipient VARCHAR(150) NOT NULL,
    language VARCHAR(2) NOT NULL,
    payload_json TEXT NOT NULL,
    status VARCHAR(20) NOT NULL,
    attempt_count INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
    idempotency_key VARCHAR(256) NOT NULL,
    provider_message_id VARCHAR(150),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    sent_at TIMESTAMP WITH TIME ZONE,
    last_error_code VARCHAR(80),
    CONSTRAINT transactional_email_outbox_pkey PRIMARY KEY (id),
    CONSTRAINT transactional_email_outbox_user_fk
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT transactional_email_outbox_idempotency_key_unique UNIQUE (idempotency_key),
    CONSTRAINT transactional_email_outbox_type_check CHECK (
        event_type IN ('WELCOME', 'NEW_SIGN_IN', 'PASSWORD_CHANGED', 'PASSWORD_RESET_COMPLETED')
    ),
    CONSTRAINT transactional_email_outbox_language_check CHECK (language IN ('es', 'en')),
    CONSTRAINT transactional_email_outbox_status_check CHECK (
        status IN ('PENDING', 'PROCESSING', 'RETRY', 'SENT', 'DEAD')
    )
);

CREATE INDEX transactional_email_outbox_pending_idx
    ON transactional_email_outbox (status, next_attempt_at, id);

CREATE TABLE email_delivery_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    event_type VARCHAR(40) NOT NULL,
    user_id BIGINT,
    recipient VARCHAR(150) NOT NULL,
    language VARCHAR(2) NOT NULL,
    provider VARCHAR(30) NOT NULL,
    provider_message_id VARCHAR(150),
    status VARCHAR(20) NOT NULL,
    error_code VARCHAR(80),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT email_delivery_audit_pkey PRIMARY KEY (id),
    CONSTRAINT email_delivery_audit_user_fk
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT email_delivery_audit_language_check CHECK (language IN ('es', 'en')),
    CONSTRAINT email_delivery_audit_status_check CHECK (
        status IN ('REQUESTED', 'SENT', 'FAILED')
    )
);

CREATE INDEX email_delivery_audit_user_created_idx
    ON email_delivery_audit (user_id, created_at);
