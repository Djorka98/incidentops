CREATE TABLE password_reset_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT,
    token_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT password_reset_tokens_pkey PRIMARY KEY (id),
    CONSTRAINT password_reset_tokens_token_hash_key UNIQUE (token_hash),
    CONSTRAINT password_reset_tokens_user_fk
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX password_reset_tokens_user_active_idx
    ON password_reset_tokens (user_id, used_at, expires_at);

CREATE TABLE security_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT,
    email_normalized VARCHAR(150),
    event_type VARCHAR(50) NOT NULL,
    ip_address VARCHAR(45),
    user_agent VARCHAR(512),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT security_events_pkey PRIMARY KEY (id),
    CONSTRAINT security_events_user_fk
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT security_events_type_check CHECK (
        event_type IN ('PASSWORD_CHANGED', 'PASSWORD_RESET_REQUESTED', 'PASSWORD_RESET_COMPLETED')
    )
);

CREATE INDEX security_events_user_type_created_idx
    ON security_events (user_id, event_type, created_at);
CREATE INDEX security_events_email_type_created_idx
    ON security_events (email_normalized, event_type, created_at);
CREATE INDEX security_events_ip_type_created_idx
    ON security_events (ip_address, event_type, created_at);
